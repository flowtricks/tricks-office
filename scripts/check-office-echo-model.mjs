import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as T from 'three';
import {loadTestModel} from './load-test-model.mjs';
import {createEchoDot} from '../src/scripts/office-echo.ts';
const model = (await loadTestModel('public/models/echo-dot.glb')).scene;
const bounds = new T.Box3().setFromObject(model, true);
const size = bounds.getSize(new T.Vector3());
assert.ok(Math.abs(size.x - .47) < .001 && Math.abs(size.z - .47) < .001, 'Original floor footprint retained');
assert.ok(size.y > .20 && size.y < .22, 'Echo sits flat rather than on its side');
assert.ok(Math.abs(bounds.min.y) < 1e-6, 'Base sits on the floor');
const echo = createEchoDot(model);
assert.ok(echo.children.includes(model), 'Uses supplied model, not a procedural replacement');
assert.ok(echo.children.some(child => child.isPointLight && child.intensity > 0), 'Blue ring light retained');
const bytes=fs.readFileSync('public/models/echo-dot.glb');
const gltf=JSON.parse(bytes.subarray(20,20+bytes.readUInt32LE(12)));
const material=gltf.materials[0];
assert.ok(material.normalTexture && material.emissiveTexture && material.pbrMetallicRoughness.baseColorTexture && material.pbrMetallicRoughness.metallicRoughnessTexture, 'Source PBR textures preserved');
console.log('PASS: Echo Dot rests flat on the floor, retains footprint, source materials and ring light.');
